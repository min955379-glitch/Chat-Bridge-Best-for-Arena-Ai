#!/usr/bin/env python3
"""Rebuild SOURCE.md from the files in extension/.

Every file is shown inside a 4-backtick fence, so files that themselves
contain ``` (like extract.js) still display correctly on GitHub.
"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(ROOT)  # repo root, because this script lives in dev/
EXT = os.path.join(ROOT, 'extension')

FILES = [
    ('manifest.json', 'json'),
    ('background.js', 'js'),
    ('content.js', 'js'),
    ('selectors.js', 'js'),
    ('extract.js', 'js'),
    ('api-client.js', 'js'),
    ('helper.js', 'js'),
    ('common.js', 'js'),
    ('popup.html', 'html'),
    ('popup.js', 'js'),
    ('popup.css', 'css'),
    ('README.html', 'html'),
]

# The anchor is the file name with the dot removed and made lower case,
# exactly as the first version of this document used it.
def anchor_for(name):
    return name.replace('.', '').lower()

HEADER = """# Chat Bridge — complete source of every file

Every file below is exactly what is in the `extension/` folder. You can copy them one by one, or use the folder as-is.

Install: `chrome://extensions` → Developer mode → **Load unpacked** → choose the `extension` folder.

## Contents

"""

FOOTER = """## icons/

The three icons are binary PNG files. They are included in the folder. To regenerate them, run `python3 dev/make-icons.py` (needs Pillow).
"""


def main():
    parts = [HEADER]
    for name, _lang in FILES:
        parts.append('- [`%s`](#%s)\n' % (name, anchor_for(name)))
    parts.append('- `icons/icon16.png`, `icons/icon48.png`, `icons/icon128.png` '
                 '(binary images, generated by `dev/make-icons.py`)\n')
    parts.append('\n---\n')

    for name, lang in FILES:
        path = os.path.join(EXT, name)
        with open(path, 'r', encoding='utf-8') as handle:
            text = handle.read()
        if not text.endswith('\n'):
            text += '\n'
        anchor = anchor_for(name)
        # Count the same way the original document did: a file that ends
        # with a newline therefore reports one more line than it has.
        lines = len(text.split('\n'))
        parts.append('\n## %s\n\n<a id="%s"></a>\n\n*%d lines.*\n\n````%s\n%s````\n'
                     % (name, anchor, lines, lang, text))
        parts.append('\n---\n')

    parts.append('\n' + FOOTER)
    out = ''.join(parts)
    with open(os.path.join(ROOT, 'SOURCE.md'), 'w', encoding='utf-8') as handle:
        handle.write(out)
    print('SOURCE.md written: %d bytes' % len(out.encode('utf-8')))


if __name__ == '__main__':
    main()
